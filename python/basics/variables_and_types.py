# Variables in python are dynamically typed

# Variable naming conventions:
# 1. Variable names can contain letters, numbers, and underscores.
# 2. Variable names cannot start with a digit
# 3. Variable names are case-sensitive
# 4. Variable names should not be a reserved keyword in Python

# Variables in python are similar to pointers in C++. 
# They are references to objects in memory, not the actual value itself
# Unreferrenced objects are automatically garbage collected by the Python interpreter

# Types of variables in Python:
# 1. Local variables: Variables that are defined inside a function and can only be accessed
#    within that function.
# 2. Global variables: Variables that are defined outside of any function and can be accessed
#    from anywhere in the code.

# Build-in data types in Python:
# 1. Numeric types: 
x = 5 # int
y = 5.0 # float
z = 5 + 3j # complex

# 2. Sequence types: list, tuple, range
x = [1, 2, 3] # list
y = (1, 2, 3) # tuple
z = range(5) # range

# 3. Text type: str
x = "Hello, World!" # str

# 4. Set types: set, frozenset
x = {1, 2, 3} # set
y = frozenset([1, 2, 3]) # frozenset

# 5. Mapping type: dict
x = {"name": "John", "age": 30} # dict

# 6. Boolean type: bool
x = True # bool
y = False # bool